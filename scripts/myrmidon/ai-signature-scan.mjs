#!/usr/bin/env node
// CI gate: no AI signatures in commits and in PR text.
//
// The repository rule: commit messages, PR titles and PR bodies carry no
// "Co-Authored-By" trailer of an AI assistant, no "Generated with ..." banner,
// and no commit is authored or committed under the bot identity "OpenClaw ADM".
// A squash merge copies the trailers of the PR commits into the merge commit,
// so the PR commits are where this has to be stopped.
//
// Usage:
//   node scripts/myrmidon/ai-signature-scan.mjs --commits <base>..<head>   # commit messages, author, committer
//   printf '%s\n%s\n' "$TITLE" "$BODY" | node scripts/myrmidon/ai-signature-scan.mjs   # PR title and body from stdin
//
// Both inputs can be given in one call. The matched text is never printed:
// the report names the rule and the short sha (or "pr-text"), nothing else.
// Fail closed: an unreadable range is exit 2, never "clean".
// Exit code: 0 clean, 1 signature found, 2 usage/read error.
// History is not rewritten: only the commits of the range are looked at.

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import { fileURLToPath } from "node:url";

// The patterns are built from parts so that this file (and its test) does not
// contain the very strings it forbids.
const AI = "(?:claude|anthropic)";

export const TEXT_RULES = [
  {
    name: "ai-co-authored-by",
    // a trailer naming an AI assistant or the noreply address of its vendor
    re: new RegExp(`^[ \\t>*-]*co-authored-by[ \\t]*:[^\\n]*(?:noreply@anthropic\\.com|\\b${AI}\\b)`, "im"),
  },
  {
    name: "ai-generated-banner",
    // "Generated with Claude Code", "Generated by Claude", "🤖 Generated with ..."
    re: new RegExp(`generated[ \\t]+(?:with|by)[ \\t]+\\[?[ \\t]*${AI}`, "i"),
  },
  {
    name: "ai-generated-robot-banner",
    re: /\u{1F916}[ \t]*generated[ \t]+with/iu,
  },
];

const BOT_IDENTITY = new Set(["openclaw adm"]);

function normalizeName(value) {
  return String(value ?? "").trim().replace(/\s+/g, " ").toLowerCase();
}

/** Findings in one piece of free text (a commit message, a PR title or body). */
export function scanSignatureText(text) {
  const findings = [];
  for (const rule of TEXT_RULES) {
    if (rule.re.test(text)) findings.push(rule.name);
  }
  return findings;
}

/** Findings of one commit: its message, its author and its committer. */
export function scanCommit(commit) {
  const findings = scanSignatureText(commit.message ?? "");
  if (BOT_IDENTITY.has(normalizeName(commit.authorName))) findings.push("bot-author");
  if (BOT_IDENTITY.has(normalizeName(commit.committerName))) findings.push("bot-committer");
  return findings;
}

const FIELD = "\u001f";
const RECORD = "\u001e";

/** Parses `git log --format=%H<US>%an<US>%cn<US>%B<RS>` output. */
export function parseGitLog(raw) {
  return raw
    .split(RECORD)
    .map((chunk) => chunk.replace(/^\n+/, ""))
    .filter((chunk) => chunk.length > 0)
    .map((chunk) => {
      const [sha, authorName, committerName, ...rest] = chunk.split(FIELD);
      return { sha, authorName, committerName, message: rest.join(FIELD) };
    });
}

export function readCommits(range, git = spawnSync) {
  const result = git(
    "git",
    ["log", `--format=%H${FIELD}%an${FIELD}%cn${FIELD}%B${RECORD}`, range],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  if (result.error || result.status !== 0) {
    throw new Error(`git log ${range} failed`);
  }
  return parseGitLog(result.stdout);
}

export function main(argv, io = {}) {
  const log = io.log ?? console.log;
  const err = io.error ?? console.error;
  let range = null;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--commits") {
      range = argv[++i];
      if (!range) {
        err("--commits requires a <base>..<head> range");
        return 2;
      }
    } else {
      err(`Unknown argument: ${argv[i]}`);
      return 2;
    }
  }

  const problems = [];
  let commitCount = 0;
  if (range) {
    let commits;
    try {
      commits = (io.readCommits ?? readCommits)(range);
    } catch (e) {
      err(e instanceof Error ? e.message : String(e));
      return 2;
    }
    commitCount = commits.length;
    for (const commit of commits) {
      for (const rule of scanCommit(commit)) problems.push({ where: `commit ${commit.sha.slice(0, 10)}`, rule });
    }
  }

  const stdin = io.stdin ?? (range ? null : fs.readFileSync(0, "utf8"));
  if (stdin !== null && stdin !== undefined && stdin !== "") {
    for (const rule of scanSignatureText(stdin)) problems.push({ where: "pr-text", rule });
  }

  if (problems.length === 0) {
    log(`ai-signature: clean (${commitCount} commit(s) checked${range ? "" : ", text only"})`);
    return 0;
  }
  log(`ai-signature: ${problems.length} finding(s)`);
  for (const p of problems) log(`  ${p.where}: ${p.rule}`);
  log("Remove the AI signature (trailer or banner) and set the author to the repository identity; do not rewrite main.");
  return 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exit(main(process.argv.slice(2)));
}
