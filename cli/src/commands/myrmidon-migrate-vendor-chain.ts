import { listMigrationChain, loadMigrationTargetSchema, type MigrationTargetSchema } from "@paperclipai/db";
import { VENDOR_EXTRA_RELEASES } from "./myrmidon-migrate-vendor-releases.js";

// The vendor Paperclip releases this tool migrates from, and the shape of their
// migration chains. All supported releases share the same first 278 migrations
// (journal idx 0..279). Those hashes are not copied here: the first 278
// migrations of this tree are byte-identical to the base release and, by
// repository rule, never change, so they are read from the migration files at
// run time. A drift in length or in the last tag fails loudly.
//
// Later releases add migrations of their own. Their (tag, sha256) are pinned in
// myrmidon-migrate-vendor-releases.ts, generated by
// scripts/myrmidon/vendor-release-add.mjs.
export const PAPERCLIP_VENDOR_RELEASE = "v2026.916.1";
export const PAPERCLIP_VENDOR_LAST_IDX = 279;
export const PAPERCLIP_VENDOR_LENGTH = 278;
export const PAPERCLIP_VENDOR_LAST_TAG = "0279_tired_deathstrike";

export type VendorChainEntry = readonly [tag: string, sha256: string, when: number];

/** One migration of a later release: pinned hash and what it adds to the schema. */
export type VendorExtraMigration = {
  tag: string;
  sha256: string;
  when: number;
  /** Tables the migration creates. */
  tables: ReadonlyArray<string>;
  /** Columns the migration adds, as `table.column`. */
  columns: ReadonlyArray<string>;
};
export type VendorReleaseExtra = { release: string; extra: ReadonlyArray<VendorExtraMigration> };

export type VendorRelease = {
  release: string;
  chain: ReadonlyArray<VendorChainEntry>;
};

/** What a later release added, with the release that introduced it. */
export type VendorOnlyIndex = {
  tables: ReadonlyMap<string, string>;
  /** Key `table.column`. */
  columns: ReadonlyMap<string, string>;
  droppedTables?: ReadonlySet<string>;
  droppedColumns?: ReadonlySet<string>;
};

export type TargetSchemaLookup = {
  tables: ReadonlySet<string>;
  columns: ReadonlySet<string>;
};

let cachedBase: Promise<ReadonlyArray<VendorChainEntry>> | null = null;

/** The chain shared by every supported release (the base release, v2026.916.1). */
export function loadVendorChain(): Promise<ReadonlyArray<VendorChainEntry>> {
  cachedBase ??= listMigrationChain().then((all) => {
    const vendor = all.filter((e) => e.idx <= PAPERCLIP_VENDOR_LAST_IDX).map((e) => [e.tag, e.hash, e.when] as const);
    if (vendor.length !== PAPERCLIP_VENDOR_LENGTH || vendor[vendor.length - 1]![0] !== PAPERCLIP_VENDOR_LAST_TAG) {
      throw new Error("The vendor part of the migration journal does not have the pinned shape; refusing to judge a source.");
    }
    return vendor;
  });
  return cachedBase;
}

/** Builds the supported releases, oldest first, from the base chain and the pinned extras. */
export function buildVendorReleases(
  base: ReadonlyArray<VendorChainEntry>,
  extras: ReadonlyArray<VendorReleaseExtra> = VENDOR_EXTRA_RELEASES,
): VendorRelease[] {
  return [
    { release: PAPERCLIP_VENDOR_RELEASE, chain: base },
    ...extras.map((r) => ({
      release: r.release,
      chain: [...base, ...r.extra.map((e) => [e.tag, e.sha256, e.when] as const)],
    })),
  ];
}

export async function loadVendorReleases(): Promise<VendorRelease[]> {
  return buildVendorReleases(await loadVendorChain());
}

/**
 * Tables and columns that exist only in later releases and are absent from
 * the target schema, taking into account net migration chain state (additions and drops).
 */
export function buildVendorOnlyIndex(
  extras: ReadonlyArray<VendorReleaseExtra> = VENDOR_EXTRA_RELEASES,
  targetSchema?: TargetSchemaLookup,
): VendorOnlyIndex {
  const tables = new Map<string, string>();
  const columns = new Map<string, string>();
  const droppedTables = new Set<string>();
  const droppedColumns = new Set<string>();

  for (const r of extras) {
    for (const e of r.extra) {
      for (const t of e.tables) {
        if (!tables.has(t) && (!targetSchema || !targetSchema.tables.has(t))) {
          tables.set(t, r.release);
        }
      }
      for (const c of e.columns) {
        if (!columns.has(c) && (!targetSchema || !targetSchema.columns.has(c))) {
          columns.set(c, r.release);
        }
      }

      const explicitDropTables = (e as any).dropTables as ReadonlyArray<string> | undefined;
      if (explicitDropTables) {
        for (const t of explicitDropTables) {
          tables.delete(t);
          droppedTables.add(t);
          for (const colKey of columns.keys()) {
            if (colKey.startsWith(`${t}.`)) {
              columns.delete(colKey);
              droppedColumns.add(colKey);
            }
          }
        }
      }
      const explicitDropColumns = (e as any).dropColumns as ReadonlyArray<string> | undefined;
      if (explicitDropColumns) {
        for (const c of explicitDropColumns) {
          columns.delete(c);
          droppedColumns.add(c);
        }
      }

      const dropMatch = /^\d+_drop_(.+)$/.exec(e.tag);
      if (dropMatch) {
        const dropTarget = dropMatch[1];
        if (tables.has(dropTarget)) {
          tables.delete(dropTarget);
          droppedTables.add(dropTarget);
          for (const colKey of columns.keys()) {
            if (colKey.startsWith(`${dropTarget}.`)) {
              columns.delete(colKey);
              droppedColumns.add(colKey);
            }
          }
        }
        for (const colKey of [...columns.keys()]) {
          if (colKey.replace(".", "_") === dropTarget) {
            columns.delete(colKey);
            droppedColumns.add(colKey);
          }
        }
        if (dropTarget.includes("_")) {
          const sepIdx = dropTarget.indexOf("_");
          const candidateKey = `${dropTarget.slice(0, sepIdx)}.${dropTarget.slice(sepIdx + 1)}`;
          columns.delete(candidateKey);
          droppedColumns.add(candidateKey);
        }
      }
    }
  }
  return { tables, columns, droppedTables, droppedColumns };
}

/**
 * Resolves the target schema from our migration tree and builds the vendor-only
 * index containing only features that Myrmidon's target schema really lacks.
 */
export async function loadVendorOnlyIndex(
  extras: ReadonlyArray<VendorReleaseExtra> = VENDOR_EXTRA_RELEASES,
  targetSchema?: TargetSchemaLookup,
): Promise<VendorOnlyIndex> {
  const resolvedTarget = targetSchema ?? (await loadMigrationTargetSchema());
  return buildVendorOnlyIndex(extras, resolvedTarget);
}

