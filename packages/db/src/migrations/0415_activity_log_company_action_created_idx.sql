-- myrmidon(DB-CARE / 1.6.6 DEFECT): the rc.15 board outage of 24.10.2026 —
-- /api/health answered in 10-20 s and the fleet's API calls timed out while
-- myrmidon-pg sat at 267% CPU. pg_stat_activity showed the feature health
-- pass (server/src/myrmidon/features, every 5 min per process plus the
-- features page poll) running
--   select max(created_at) from activity_log
--   where company_id in (...) and action in (...) and created_at >= ...
--     [and details ->> $key = $value]
-- for 3-10 s per call: 1.15M rows / 1.5 GB with no index carrying "action",
-- so every call was a table-wide filter over (company_id, created_at) ranges.
--
-- This index serves both the chat-holds feature health leg
-- (action = 'issue.execution_recovery_settled' AND
--  details ->> 'continuation' = 'chat_owner_message') and the swarm-claim leg
-- (action = 'issue.swarm_claim.claimed'): the leading (company_id, action)
-- pair resolves to the tiny action slice per company, and created_at DESC
-- lets max(created_at) read the first matching entry and stop. The
-- details->>'continuation' residual is evaluated only on that slice, so the
-- plain composite is sufficient; a details-keyed partial index is not needed
-- (the action slice is a few rows against 1.15M).
--
-- The lookup leg is generated by server/src/myrmidon/features/ports.ts
-- (activity.latest); it is bounded by company ids, one action and a 7-day
-- lookback, so the index shape matches the where-clause prefix exactly.
--
-- Build cost on the production table (1.15M rows, 1.5 GB): a btree over the
-- whole table. Drizzle migrations run inside one transaction, so
-- CONCURRENTLY is unavailable — the same accepted trade-off as 0307/0308/
-- 0381. The migration runs at deploy time before the server starts serving
-- the features report; expect an index build on the order of tens of
-- seconds to ~2 minutes on the production instance, once, forward-only.
-- paperclip:migration-safety-ignore large-create-index-not-concurrently: Drizzle migrations run transactionally, so CONCURRENTLY is unavailable; this forward-only index is required to serve the feature-health activity_log lookups (1.6.6 board latency defect).
CREATE INDEX IF NOT EXISTS "activity_log_company_action_created_idx" ON "activity_log" USING btree ("company_id","action","created_at" DESC);
