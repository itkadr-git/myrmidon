describe("project default caste API", () => {
  beforeEach(() => {
    vi.resetModules();
    registerModuleMocks();
    vi.clearAllMocks();
    mockAccessService.decide.mockResolvedValue({ allowed: true });
  });
  it("PATCH and GET round trip the field including null", async () => {
    const id = "11111111-2222-4333-8444-555555555555";
    let project = buildProject({ id, defaultCasteKey: null });
    mockProjectService.getById.mockImplementation(async () => project);
    mockProjectService.update.mockImplementation(async (_id, body) => {
      project = { ...project, ...body };
      return project;
    });
    const app = await createApp();
    for (const key of ["engineer", null]) {
      const patched = await request(app).patch(`/api/projects/${id}`).send({ defaultCasteKey: key });
      expect(patched.status).toBe(200);
      expect(patched.body.defaultCasteKey).toBe(key);
      const fetched = await request(app).get(`/api/projects/${id}`);
      expect(fetched.status).toBe(200);
      expect(fetched.body.defaultCasteKey).toBe(key);
    }
  }, 60_000);
  it("rejects malformed keys before persistence", async () => {
    const app = await createApp();
    const result = await request(app).patch("/api/projects/11111111-2222-4333-8444-555555555555").send({ defaultCasteKey: "INVALID key" });
    expect(result.status).toBe(400);
    expect(mockProjectService.update).not.toHaveBeenCalled();
  });
});
